const fs = require('fs');
const f = process.argv[2] || '/Users/abhay/tipto-clone/home.html';
const h = fs.readFileSync(f, 'utf8');
const head = h.split('</head>')[0];
const metas = head.match(/<meta[^>]*>/g) || [];
console.log('=== META TAGS ===');
metas.forEach(m => console.log(m));
console.log('\n=== TITLE ===');
console.log((head.match(/<title[^>]*>[\s\S]*?<\/title>/g) || []).join('\n'));
console.log('\n=== LINKS (rel) ===');
(head.match(/<link[^>]*>/g) || []).forEach(l => console.log(l));
console.log('\n=== SCRIPTS ===');
(head.match(/<script[^>]*>/g) || []).forEach(l => console.log(l));
console.log('\n=== NOSCRIPT ===');
(head.match(/<noscript[\s\S]*?<\/noscript>/g) || []).forEach(l => console.log(l.slice(0, 800)));
console.log('\n=== JSON-LD ===');
const lds = h.match(/<script type="application\/ld\+json"[\s\S]*?<\/script>/g) || [];
lds.forEach(l => console.log(l));
console.log('\n=== OG/TWITTER ===');
metas.filter(m => /og:|twitter:|canonical/i.test(m)).forEach(m => console.log(m));
